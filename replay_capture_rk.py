"""Seekable NVDEC replay, resized before conversion to BGR on the DGX.

Implements the VideoCapture methods used by StudioController. The source is a
locally remuxed MKV with millisecond PTS generated by hk_replay_fetch.remux_mkv.
The single-camera app retains its existing OpenCV capture factory.
"""
import json
import logging

import cv2
import numpy as np

LOG = logging.getLogger(__name__)


class HardwareReplayCapture:
    def __init__(self, info, width, report=lambda text: None):
        import gi
        gi.require_version('Gst', '1.0')
        gi.require_version('GstApp', '1.0')
        from gi.repository import Gst, GstApp
        if not Gst.is_initialized():
            Gst.init(None)
        if Gst.ElementFactory.find('nvh265dec') is None:
            raise RuntimeError('nvh265dec unavailable')
        self.Gst = Gst
        self.fps = info['fps']
        self.frames = info['frames']
        self.report = report
        self.position = 0
        self.seek_failed = False
        width = int(width or 2448) & ~1
        height = int(round(width * 2048 / 2448)) & ~1
        self.pipe = Gst.parse_launch(
            'filesrc location=%s ! matroskademux ! h265parse ! nvh265dec ! '
            'videoscale ! video/x-raw,format=NV12,width=%d,height=%d ! '
            'appsink name=sink max-buffers=2 drop=false sync=false'
            % (json.dumps(info['mkv']), width, height))
        self.sink = self.pipe.get_by_name('sink')
        self.bus = self.pipe.get_bus()
        if self.pipe.set_state(Gst.State.PLAYING) == Gst.StateChangeReturn.FAILURE:
            self.release()
            raise RuntimeError('NVDEC replay pipeline failed to start')
        # A filesrc pipeline starts asynchronously. Seeking before demux has
        # discovered the stream can fail and look like an empty segment.
        result, state, pending = self.pipe.get_state(3 * Gst.SECOND)
        if result != Gst.StateChangeReturn.SUCCESS:
            self.release()
            raise RuntimeError('NVDEC replay preroll did not complete')

    def isOpened(self):
        return self.pipe is not None

    def get(self, prop):
        if prop == cv2.CAP_PROP_FPS:
            return self.fps
        if prop == cv2.CAP_PROP_FRAME_COUNT:
            return self.frames
        if prop == cv2.CAP_PROP_POS_FRAMES:
            return self.position
        if prop == cv2.CAP_PROP_POS_MSEC:
            return round(self.position * 1000 / self.fps)
        return 0

    def set(self, prop, value):
        if prop != cv2.CAP_PROP_POS_FRAMES or self.pipe is None:
            return False
        frame = max(0, min(self.frames-1, int(value)))
        # Seek to the exact millisecond PTS written by remux_mkv. An unrounded
        # f/fps target can land in the preceding frame's duration interval.
        target = round(frame * 1000 / self.fps) * self.Gst.MSECOND
        ok = self.pipe.seek_simple(self.Gst.Format.TIME,
                                   self.Gst.SeekFlags.FLUSH | self.Gst.SeekFlags.ACCURATE,
                                   target)
        self.seek_failed = not ok
        if ok:
            self.position = frame
        else:
            self.report('回放硬件解码定位失败，请重新打开片段')
        return ok

    def read(self):
        if self.pipe is None or self.seek_failed:
            return False, None
        sample = self.sink.emit('try-pull-sample', 2 * self.Gst.SECOND)
        if sample is None:
            message = self.bus.timed_pop_filtered(0, self.Gst.MessageType.ERROR)
            if message is not None:
                error, debug = message.parse_error()
                LOG.error('Replay NVDEC error: %s (%s)', error, debug)
                self.report('回放硬件解码错误：' + error.message)
            elif not self.sink.is_eos():
                self.report('回放硬件解码等待超时')
            return False, None
        caps = sample.get_caps().get_structure(0)
        width, height = caps.get_value('width'), caps.get_value('height')
        buffer = sample.get_buffer()
        ok, mapped = buffer.map(self.Gst.MapFlags.READ)
        if not ok:
            return False, None
        try:
            # GStreamer video buffers pad each NV12 row to a multiple of four.
            stride = (width + 3) & ~3
            nv12 = np.frombuffer(mapped.data, dtype=np.uint8).reshape(height*3//2, stride)
            image = cv2.cvtColor(nv12[:, :width], cv2.COLOR_YUV2BGR_NV12)
        finally:
            buffer.unmap(mapped)
        self.position += 1
        return True, image

    def release(self):
        if self.pipe is not None:
            self.pipe.set_state(self.Gst.State.NULL)
            self.pipe = None


def open_replay(info, width, report):
    try:
        capture = HardwareReplayCapture(info, width, report)
        LOG.info('Replay NVDEC opened: %s', info['mkv'])
        return capture
    except Exception:
        LOG.exception('Replay NVDEC unavailable; using OpenCV software decoder')
        report('回放硬解不可用，回退软件解码（四路同时播放可能降速）')
        return cv2.VideoCapture(info['mkv'])
